#!/usr/bin/env bash
# check-py-lock.sh - verifikasi services/<svc>/requirements.lock SINKRON dengan requirements.txt dan ber-hash penuh
# (SEC-214). Tanpa jaringan, tanpa Python (bash + awk; jalan di CI dan Git Bash). Runbook:
# docs/runbooks/python-dependency-lock.md.
#
# Pemakaian:  bash scripts/check-py-lock.sh [service...]     (default: daftar LOCKED_SERVICES di bawah)
# Gagal bila:
#   - lock tidak ada / masih placeholder (EFN_LOCK_PLACEHOLDER) / bukan keluaran pip-compile Python 3.12;
#   - ada entri lock tanpa pin `==` atau tanpa --hash=sha256:<64 hex>, atau opsi pip (-e, --index-url, --find-links,
#     --extra-index-url, --trusted-host, URL) di lock;
#   - requirements.txt memuat baris selain pin `nama==versi` (penanda lingkungan boleh);
#   - himpunan dependency langsung di lock (anotasi `via -r requirements.txt`) != pin di requirements.txt, atau
#     versinya berbeda (requirements.txt diubah tanpa menjalankan scripts/lock-python-deps.sh).
# Kelengkapan dependency transitif dibuktikan saat install: Dockerfile & CI `pip install --require-hashes --no-deps`
# lalu `pip check`.
set -euo pipefail
export LC_ALL=C

# Service Python yang WAJIB punya lock (SEC-214). Service lain menyusul (runbook §Service baru).
LOCKED_SERVICES=(forecast-worker)

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fail=0
err() { echo "check-py-lock: $*" >&2; fail=1; }
norm() { # PEP 503: huruf kecil, rangkaian [-_.] -> '-'
  local n="${1,,}"
  sed -E 's/[-_.]+/-/g' <<< "$n"
}

check_service() {
  local svc="$1" dir req lock line name ver rest kind cnt direct
  [[ "$svc" =~ ^[a-z0-9][a-z0-9-]{0,40}$ ]] || { err "nama service tidak valid: $svc"; return; }
  dir="$root/services/$svc"; req="$dir/requirements.txt"; lock="$dir/requirements.lock"
  [[ -f "$req" ]] || { err "$svc: requirements.txt tidak ada"; return; }
  if [[ ! -s "$lock" ]]; then err "$svc: requirements.lock tidak ada (bash scripts/lock-python-deps.sh $svc)"; return; fi
  if grep -q 'EFN_LOCK_PLACEHOLDER' "$lock"; then
    err "$svc: requirements.lock masih placeholder - jalankan 'bash scripts/lock-python-deps.sh $svc' (SEC-214)"; return
  fi
  grep -q 'autogenerated by pip-compile with Python 3\.12' "$lock" \
    || err "$svc: requirements.lock bukan keluaran pip-compile Python 3.12 (pakai scripts/lock-python-deps.sh)"
  if grep -nE '^[[:space:]]*(-e|--editable|--index-url|-i |--extra-index-url|--find-links|-f |--trusted-host|--no-binary|--pre)|://' "$lock" \
       | grep -vE '^[0-9]+:[[:space:]]*#' > /dev/null; then
    err "$svc: requirements.lock memuat opsi pip/URL (indeks/sumber lain dilarang)"
  fi

  # Pin langsung requirements.txt -> want[nama]=versi
  local -A want=() got=() is_direct=()
  while IFS= read -r line || [[ -n "$line" ]]; do
    line="${line%%#*}"; line="${line%$'\r'}"
    line="${line#"${line%%[![:space:]]*}"}"; line="${line%"${line##*[![:space:]]}"}"
    [[ -z "$line" ]] && continue
    if [[ "$line" =~ ^([A-Za-z0-9][A-Za-z0-9._-]*)(\[[A-Za-z0-9,._-]+\])?==([A-Za-z0-9.+!_-]+)([[:space:]]*;.*)?$ ]]; then
      name="$(norm "${BASH_REMATCH[1]}")"
      [[ -z "${want[$name]:-}" ]] || err "$svc: requirements.txt memuat $name dua kali"
      want[$name]="${BASH_REMATCH[3]}"
    else
      err "$svc: requirements.txt baris bukan pin '==': $line"
    fi
  done < "$req"
  (( ${#want[@]} > 0 )) || err "$svc: requirements.txt tanpa pin"

  # Entri lock: "<kind> <nama> <versi> <jumlah hash> <direct 0|1>"
  while read -r kind name ver cnt direct rest; do
    [[ -n "${rest:-}" ]] && { err "$svc: baris lock tak terduga: $kind $name"; continue; }
    case "$kind" in
      PKG)
        name="$(norm "$name")"
        [[ -z "${got[$name]:-}" ]] || err "$svc: requirements.lock memuat $name dua kali"
        got[$name]="$ver"; is_direct[$name]="$direct"
        [[ "$ver" =~ ^[A-Za-z0-9.+!_-]+$ ]] || err "$svc: lock $name tanpa versi '==' yang valid"
        (( cnt > 0 )) || err "$svc: lock $name==$ver tanpa --hash=sha256 (pip --require-hashes akan menolak)"
        ;;
      BADHASH) err "$svc: lock memuat hash bukan sha256 64 hex (entri ${name})" ;;
      BADPIN)  err "$svc: lock memuat entri tanpa pin '==': ${name}" ;;
      *) err "$svc: keluaran parser tidak dikenal: $kind" ;;
    esac
  done < <(tr -d '\r' < "$lock" | awk '
    function flush() { if (name != "") { print "PKG", name, ver, h, d }; name = "" }
    /^[[:space:]]*#/ { if (name != "" && $0 ~ /-r requirements\.txt/) d = 1; next }
    /^[[:space:]]*$/ { next }
    /^[A-Za-z0-9]/ {
      flush()
      if (index($1, "==") == 0) { print "BADPIN", $1, "-", 0, 0; next }
      n = $1; sub(/==.*/, "", n); v = $1; sub(/^[^=]*==/, "", v); sub(/\[.*\]/, "", n)
      name = n; ver = v; h = 0; d = 0
      next
    }
    /--hash=/ {
      line = $0; sub(/^[[:space:]]*--hash=/, "", line); sub(/[[:space:]]*\\?[[:space:]]*$/, "", line)
      if (line ~ /^sha256:[a-f0-9]+$/ && length(line) == 71) { h++ } else { print "BADHASH", name, "-", 0, 0 }
      next
    }
    END { flush() }')

  (( ${#got[@]} > 0 )) || err "$svc: requirements.lock tanpa entri paket"
  for name in "${!want[@]}"; do
    if [[ -z "${got[$name]:-}" ]]; then
      err "$svc: $name ada di requirements.txt tetapi tidak di lock (jalankan scripts/lock-python-deps.sh $svc)"
    elif [[ "${got[$name]}" != "${want[$name]}" ]]; then
      err "$svc: $name requirements.txt==${want[$name]} != lock==${got[$name]} (jalankan scripts/lock-python-deps.sh $svc)"
    elif [[ "${is_direct[$name]:-0}" != 1 ]]; then
      err "$svc: $name tidak beranotasi 'via -r requirements.txt' di lock (lock basi; buat ulang)"
    fi
  done
  for name in "${!is_direct[@]}"; do
    if [[ "${is_direct[$name]}" == 1 && -z "${want[$name]:-}" ]]; then
      err "$svc: lock menandai $name sebagai dependency langsung tetapi tidak ada di requirements.txt (lock basi)"
    fi
  done
  (( fail )) || echo "check-py-lock: $svc OK (${#want[@]} pin langsung, ${#got[@]} paket ber-hash)"
}

if (( $# > 0 )); then services=("$@"); else services=("${LOCKED_SERVICES[@]}"); fi
for s in "${services[@]}"; do check_service "$s"; done
if (( fail )); then
  echo "check-py-lock: GAGAL - docs/runbooks/python-dependency-lock.md" >&2
  exit 1
fi
